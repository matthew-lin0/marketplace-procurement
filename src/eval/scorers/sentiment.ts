/**
 * T5 scoring, in two layers.
 *
 * Layer 1 is MECHANICAL and free: fetch the cited URL, check whether the
 * verbatim quote actually appears. This is the reason the schema requires
 * verbatim quotes at all.
 *
 * Layer 2 is JUDGED: does the quote support the claim as stated. This one is
 * the easiest thing in the project to fool — a judge model evaluating claims
 * generated by the same model will happily rubber-stamp itself. Two
 * mitigations: the judge defaults to a DIFFERENT model, and the verification
 * checklist requires manually opening 10 citations before trusting the
 * aggregate.
 */

const JudgeVerdict = z.object({
  quoteAppearsOnPage: z.boolean(),
  quoteSupportsClaim: z.boolean(),
  reasoning: z.string(),
});
type JudgeVerdict = z.infer<typeof JudgeVerdict>;

export interface AttributionScore {
  totalCitations: number;
  /** Layer 1. Mechanical, cheap, and the one to trust most. */
  quoteMatchRate: number;
  /** Layer 2. Judged, and therefore the one to audit by hand. */
  judgedSupportRate: number;
  fetchFailures: number;
  judgedN: number;
}

export interface FetchedPage {
  url: string;
  text: string | null;
}

export type PageFetcher = (url: string) => Promise<string | null>;

/**
 * Below this, an HTTP 200 is a bot-check page or a JS shell rather than real
 * content. Measured: a www.reddit.com comment thread returns 200 with 37
 * usable characters; the same thread on old.reddit.com returns 49,689.
 *
 * This distinction is load-bearing. A thin page counts as a FETCH FAILURE
 * (reported separately, excluded from the denominator), not as a missing quote
 * (which counts against attribution accuracy). Conflating them would drive T5
 * to ~0%, trip the gate, and blame the model for a broken verifier.
 */
const MIN_USABLE_CHARS = 500;

/**
 * Rewrites hosts that serve client-rendered shells to equivalents that serve
 * static HTML. Reddit is the one that matters here, since it is where most of
 * T5's evidence lives.
 *
 * Durability note: this is zero-setup and works today, but old.reddit.com is
 * not contractually permanent. The Reddit Data API (OAuth) is the durable
 * path — see `redditApiFetcher` below.
 */
export function verifiableUrl(url: string): string {
  try {
    const u = new URL(url);
    if (u.hostname === 'www.reddit.com' || u.hostname === 'reddit.com') {
      u.hostname = 'old.reddit.com';
      return u.toString();
    }
    return url;
  } catch {
    return url;
  }
}

export const defaultFetcher: PageFetcher = async (url) => {
  try {
    const res = await fetch(verifiableUrl(url), {
      headers: { 'user-agent': 'marketplace-eval/0.1 (attribution verification)' },
      signal: AbortSignal.timeout(20_000),
    });
    if (!res.ok) return null;
    const text = stripHtml(await res.text());
    // A 200 that carries no content is a failed fetch, not an absent quote.
    return text.length < MIN_USABLE_CHARS ? null : text;
  } catch {
    return null;
  }
};

/**
 * Optional upgrade path: the Reddit Data API.
 *
 * Needs REDDIT_CLIENT_ID and REDDIT_CLIENT_SECRET (register a "script" app at
 * reddit.com/prefs/apps). Returns clean comment bodies rather than stripped
 * HTML, so verbatim quote matching is exact instead of whitespace-approximate.
 *
 * Not the default: `defaultFetcher` needs no credentials and was measured
 * working. Use this when you want durability, or when old.reddit stops serving
 * static HTML.
 */
export function redditApiFetcher(fallback: PageFetcher = defaultFetcher): PageFetcher {
  let token: { value: string; expiresAt: number } | null = null;

  const getToken = async (): Promise<string | null> => {
    const id = process.env.REDDIT_CLIENT_ID;
    const secret = process.env.REDDIT_CLIENT_SECRET;
    if (!id || !secret) return null;
    if (token && Date.now() < token.expiresAt) return token.value;

    const res = await fetch('https://www.reddit.com/api/v1/access_token', {
      method: 'POST',
      headers: {
        authorization: `Basic ${Buffer.from(`${id}:${secret}`).toString('base64')}`,
        'content-type': 'application/x-www-form-urlencoded',
        'user-agent': 'marketplace-eval/0.1 by u/anonymous',
      },
      body: 'grant_type=client_credentials',
      signal: AbortSignal.timeout(20_000),
    });
    if (!res.ok) return null;

    const json = (await res.json()) as { access_token?: string; expires_in?: number };
    if (!json.access_token) return null;
    // Renew a minute early rather than racing the expiry.
    token = {
      value: json.access_token,
      expiresAt: Date.now() + ((json.expires_in ?? 3600) - 60) * 1000,
    };
    return token.value;
  };

  return async (url) => {
    let host: string;
    try {
      host = new URL(url).hostname;
    } catch {
      return fallback(url);
    }
    if (!/(^|\.)reddit\.com$/.test(host)) return fallback(url);

    const bearer = await getToken();
    if (!bearer) return fallback(url);

    try {
      const u = new URL(url);
      u.hostname = 'oauth.reddit.com';
      u.pathname = u.pathname.replace(/\/?$/, '') + '.json';

      const res = await fetch(u.toString(), {
        headers: {
          authorization: `Bearer ${bearer}`,
          'user-agent': 'marketplace-eval/0.1 by u/anonymous',
        },
        signal: AbortSignal.timeout(20_000),
      });
      if (!res.ok) return fallback(url);

      // Concatenate every `body` field in the listing tree: the post selftext
      // plus all comment bodies, which is exactly the text a quote can cite.
      const bodies: string[] = [];
      collectBodies(await res.json(), bodies);
      const joined = bodies.join('\n\n');
      return joined.length < MIN_USABLE_CHARS ? fallback(url) : joined;
    } catch {
      return fallback(url);
    }
  };
}

function collectBodies(node: unknown, out: string[]): void {
  if (Array.isArray(node)) {
    for (const n of node) collectBodies(n, out);
    return;
  }
  if (!node || typeof node !== 'object') return;
  const obj = node as Record<string, unknown>;
  if (typeof obj['selftext'] === 'string' && obj['selftext']) out.push(obj['selftext']);
  if (typeof obj['body'] === 'string' && obj['body']) out.push(obj['body']);
  for (const v of Object.values(obj)) collectBodies(v, out);
}

export async function scoreAttribution(
  results: SentimentResult[],
  opts: { client?: ModelClient; fetcher?: PageFetcher; judgeModel?: string } = {},
): Promise<AttributionScore> {
  const fetcher = opts.fetcher ?? defaultFetcher;
  const judgeModel = opts.judgeModel ?? MODELS.judge;

  let totalCitations = 0;
  let quoteMatches = 0;
  let fetchFailures = 0;
  let judgedN = 0;
  let judgedSupported = 0;

  const pageCache = new Map<string, string | null>();

  for (const result of results) {
    for (const finding of result.findings) {
      for (const citation of finding.citations) {
        totalCitations++;

        if (!pageCache.has(citation.url)) {
          pageCache.set(citation.url, await fetcher(citation.url));
        }
        const page = pageCache.get(citation.url) ?? null;

        if (page === null) {
          // Can't verify. Counted separately rather than silently as a pass —
          // a dead link is not evidence.
          fetchFailures++;
          continue;
        }

        const matched = quoteAppearsIn(citation.quote, page);
        if (matched) quoteMatches++;

        // Only judge support when the quote is real. Judging a hallucinated
        // quote tells us nothing.
        if (matched && opts.client) {
          judgedN++;
          try {
            const verdict = await opts.client.run<JudgeVerdict>({
              stage: 't5.judge',
              model: judgeModel,
              system:
                'You are a skeptical fact-checker auditing an automated research tool. Your job is to catch claims that overstate their evidence.',
              prompt: attributionJudgePrompt(finding.claim, citation.quote, page),
              schema: JudgeVerdict,
            });
            if (verdict.parsed?.quoteSupportsClaim) judgedSupported++;
          } catch {
            // Judge failure is not support.
          }
        }
      }
    }
  }

  const verifiable = totalCitations - fetchFailures;
  return {
    totalCitations,
    quoteMatchRate: verifiable > 0 ? quoteMatches / verifiable : 0,
    judgedSupportRate: judgedN > 0 ? judgedSupported / judgedN : 0,
    fetchFailures,
    judgedN,
  };
}

// --- Generation scoping ----------------------------------------------------

export interface GenerationScopingScore {
  n: number;
  /** Correctly scoped OR honestly marked unknown. */
  correctlyScopedRate: number;
  /** Confidently attached to the WRONG generation. These count as errors, not
   *  misses — advice about a 2014 unit does not apply to the 2023 revision. */
  misscopedRate: number;
  unknownRate: number;
}

export function scoreGenerationScoping(
  cases: { findings: SentimentFinding[]; trueGeneration: string | null }[],
): GenerationScopingScore {
  let n = 0;
  let correct = 0;
  let misscoped = 0;
  let unknown = 0;

  for (const c of cases) {
    if (!c.trueGeneration) continue; // can't score without ground truth
    for (const f of c.findings) {
      n++;
      const claimed = f.appliesToGeneration.trim().toLowerCase();
      if (!claimed || claimed === 'unknown') {
        unknown++;
        correct++; // honest uncertainty is correct behavior
        continue;
      }
      const truth = c.trueGeneration.toLowerCase();
      // Generic scoping ("all generations") is not a misscope.
      if (claimed.includes(truth) || truth.includes(claimed) || claimed.includes('all')) {
        correct++;
      } else {
        misscoped++;
      }
    }
  }

  return {
    n,
    correctlyScopedRate: n > 0 ? correct / n : 0,
    misscopedRate: n > 0 ? misscoped / n : 0,
    unknownRate: n > 0 ? unknown / n : 0,
  };
}

// --- Actionability ---------------------------------------------------------

export interface ActionabilityScore {
  totalFindings: number;
  actionableFraction: number;
  byKind: Record<string, number>;
}

/**
 * A tool returning ten flavors of "great rack, love it" has failed even at
 * 100% attribution accuracy. Scored off the finding `kind`, which the schema
 * already forces the model to commit to, rather than a second judged pass.
 */
export function scoreActionability(results: SentimentResult[]): ActionabilityScore {
  const byKind: Record<string, number> = {};
  let total = 0;
  let actionable = 0;

  for (const r of results) {
    for (const f of r.findings) {
      total++;
      byKind[f.kind] = (byKind[f.kind] ?? 0) + 1;
      if (ACTIONABLE_SENTIMENT_KINDS.has(f.kind)) actionable++;
    }
  }

  return {
    totalFindings: total,
    actionableFraction: total > 0 ? actionable / total : 0,
    byKind,
  };
}

const NAMED_ENTITIES: Record<string, string> = {
  nbsp: ' ',
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  ndash: '-',
  mdash: '-',
  hellip: '...',
  rsquo: "'",
  lsquo: "'",
  rdquo: '"',
  ldquo: '"',
  middot: '·',
  bull: '•',
  raquo: '»',
  laquo: '«',
  deg: '°',
  times: '×',
};

/**
 * Entity decoding has to be thorough, including NUMERIC entities.
 *
 * Observed on a live old.reddit thread: stripped text retained `&#32;` (a
 * space) where the rendered page shows whitespace. A model quoting what it read
 * would then fail to match — a spurious attribution failure that looks
 * identical to a fabricated quote in the metric. Same class of silent,
 * one-directional bug as the thin-200 case above, so it gets the same
 * treatment.
 */
function decodeEntities(s: string): string {
  return s
    .replace(/&#(\d+);/g, (_, d: string) => safeCodePoint(Number.parseInt(d, 10)))
    .replace(/&#x([0-9a-f]+);/gi, (_, h: string) => safeCodePoint(Number.parseInt(h, 16)))
    .replace(/&([a-z]+);/gi, (m, name: string) => NAMED_ENTITIES[name.toLowerCase()] ?? m);
}

function safeCodePoint(cp: number): string {
  if (!Number.isFinite(cp) || cp < 0 || cp > 0x10ffff) return ' ';
  try {
    return String.fromCodePoint(cp);
  } catch {
    return ' ';
  }
}

function stripHtml(html: string): string {
  return decodeEntities(
    html
      .replace(/<script[\s\S]*?<\/script>/gi, ' ')
      .replace(/<style[\s\S]*?<\/style>/gi, ' ')
      .replace(/<[^>]+>/g, ' '),
  )
    .replace(/\s+/g, ' ')
    .trim();
}
